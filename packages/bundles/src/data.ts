import { z } from 'zod'

/** What an asset is, by file extension. */
export type AssetKind = 'js' | 'css' | 'html' | 'image' | 'font' | 'other'

/** Byte sizes of one file or a sum of files. Compressed sizes are per file, then summed. */
export interface Sizes {
  raw: number
  /** Gzip at level 9. */
  gzip: number
  /** Brotli at quality 11. */
  brotli: number
}

/** One shipped file of the build. */
export interface BundleAsset extends Sizes {
  /** Path relative to the dist directory, with `/` separators. */
  file: string
  /**
   * Stable name for matching across builds: the file with content hashes removed, e.g.
   * `assets/index-B3x9kQz1.js` → `assets/index.js`. Unique within one build.
   */
  name: string
  kind: AssetKind
  /** Raw bytes that the asset's source map attributes to an original source; 0 without a map. */
  mapped: number
}

/**
 * Bytes of a bundle attributed to one origin. `name` is an npm package name, an app module path,
 * `(app)` for all app code, or `(unmapped)` for bytes no source map explains.
 */
export interface Contribution {
  name: string
  /** Raw generated bytes. */
  bytes: number
  /** Gzip bytes estimated as the contribution's share of each asset's gzip size. */
  gzip: number
}

/** An npm package found in the bundle. */
export interface BundlePackage extends Contribution {
  /** Known versions, read from install paths (pnpm, bun) or the installed `package.json`. */
  versions: string[]
  /** Distinct install directories; more than one means the package is bundled twice. */
  instances: string[]
  /** Number of the package's source files in the bundle. */
  modules: number
  /** Entrypoints whose initial or lazy assets contain the package. */
  entrypoints: string[]
}

/** One way into the app, e.g. an HTML page or a bundler entry, with the assets it loads. */
export interface BundleEntrypoint {
  name: string
  /** Asset files loaded on first visit, relative to the dist directory. */
  initial: string[]
  /** Asset files loaded later through dynamic imports. */
  lazy: string[]
  initialSize: Sizes
  lazySize: Sizes
  /** npm packages plus `(app)` and `(unmapped)`, over initial and lazy JS and CSS, largest first. */
  packages: Contribution[]
  /** App source files, by path relative to the project root, largest first. */
  modules: Contribution[]
}

/** Everything one analysis of a build measured. Plain JSON, so it can be stored and uploaded. */
export interface BundleData {
  /** Bundler that produced the build, when it could be recognized, e.g. `vite`, `webpack`. */
  tool?: string
  /** How the build was run, when `analyzeBundle` ran it. */
  build?: { command: string[]; durationMs: number }
  assets: BundleAsset[]
  entrypoints: BundleEntrypoint[]
  /** npm packages over all JS and CSS assets, largest first. */
  packages: BundlePackage[]
  /** App source files over all assets, largest first. */
  modules: Contribution[]
  /** Raw bytes of JS and CSS no source map explains. */
  unmapped: number
}

const sizes = { raw: z.number(), gzip: z.number(), brotli: z.number() }
const sizesSchema = z.object(sizes)
const contributionSchema = z.object({ name: z.string(), bytes: z.number(), gzip: z.number() })

/** Validates `BundleData`, e.g. when a CI job uploads it. */
export const bundleDataSchema: z.ZodType<BundleData> = z.object({
  tool: z.string().optional(),
  build: z.object({ command: z.array(z.string()), durationMs: z.number() }).optional(),
  assets: z.array(
    z.object({
      ...sizes,
      file: z.string(),
      name: z.string(),
      kind: z.enum(['js', 'css', 'html', 'image', 'font', 'other']),
      mapped: z.number(),
    }),
  ),
  entrypoints: z.array(
    z.object({
      name: z.string(),
      initial: z.array(z.string()),
      lazy: z.array(z.string()),
      initialSize: sizesSchema,
      lazySize: sizesSchema,
      packages: z.array(contributionSchema),
      modules: z.array(contributionSchema),
    }),
  ),
  packages: z.array(
    contributionSchema.extend({
      versions: z.array(z.string()),
      instances: z.array(z.string()),
      modules: z.number(),
      entrypoints: z.array(z.string()),
    }),
  ),
  modules: z.array(contributionSchema),
  unmapped: z.number(),
})

/** Contribution name for app code taken together. */
export const APP = '(app)'
/** Contribution name for bytes without a source mapping. */
export const UNMAPPED = '(unmapped)'
