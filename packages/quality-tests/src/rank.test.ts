import { afterAll, beforeAll, describe, expect, test } from 'bun:test'
import { mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'

import { parseLcov } from './lcov.ts'
import { findTestTargets, rankTestTargets, reasonFor, targetScore } from './rank.ts'

let dir = ''

const files: Record<string, string> = {
  'src/session.ts': [
    'export function createSession(id: string) {',
    '  if (!id) throw new Error("id")',
    '  const at = Date.now()',
    '  if (at > 0 && id.length > 2) {',
    '    return { id, at, long: true }',
    '  }',
    '  return { id, at }',
    '}',
    '',
    'export function tiny() {',
    '  return 1',
    '}',
    '',
    'export function touched(a: number) {',
    '  if (a > 1) return a',
    '  return 0',
    '}',
    '',
  ].join('\n'),
  'src/math.ts':
    'export function add(a: number, b: number) {\n  const sum = a + b\n  return sum\n}\n',
  'src/untested.ts': 'export function lonely(x: number) {\n  const y = x * 2\n  return y\n}\n',
  'src/math.test.ts': "import { test } from 'bun:test'\n",
  'src/types.ts': 'export interface A {\n  a: number\n  b: string\n  c: boolean\n}\n',
  'src/gen.ts':
    '// Code generated by tool. DO NOT EDIT.\nexport function generated() {\n  return 1\n  // x\n}\n',
  'vite.config.ts': 'export default function config() {\n  return {}\n  // x\n}\n',
  'main.go': 'package main\n\nfunc main() {\n\tprintln(1)\n}\n',
}

// tiny is short; touched is half covered; add is fully covered.
const LCOV = `SF:src/session.ts
DA:1,1
DA:2,0
DA:3,0
DA:4,0
DA:5,0
DA:7,0
DA:10,1
DA:11,1
DA:14,1
DA:15,1
DA:16,0
BRDA:4,0,0,0
BRDA:4,0,1,0
BRDA:4,1,0,0
BRDA:4,1,1,0
end_of_record
SF:src/math.ts
DA:1,1
DA:2,1
DA:3,1
end_of_record
`

beforeAll(async () => {
  dir = await mkdtemp(join(tmpdir(), 'hk-rank-'))
  await Promise.all(
    Object.entries(files).map(async ([path, content]) => {
      await mkdir(dirname(join(dir, path)), { recursive: true })
      await writeFile(join(dir, path), content)
    }),
  )
})

afterAll(async () => {
  await rm(dir, { recursive: true, force: true })
})

describe('rankTestTargets', () => {
  test('ranks uncovered functions by gap, size, branches and churn', async () => {
    const coverage = parseLcov(LCOV)
    const targets = await findTestTargets({
      dir,
      coverage,
      churn: new Map([['src/untested.ts', 7]]),
      minLines: 3,
    })
    expect(
      targets.map((target) => [
        target.file,
        target.fn.name,
        target.covered,
        target.total,
        target.complexity,
        target.churn,
      ]),
    ).toEqual([
      ['src/untested.ts', 'lonely', 0, 4, 1, 7],
      ['src/session.ts', 'createSession', 1, 6, 3, 0],
    ])
  })

  test('without churn, the larger and more branched function wins', async () => {
    const targets = await findTestTargets({ dir, coverage: parseLcov(LCOV) })
    expect(targets.map((target) => target.fn.name)).toEqual(['createSession', 'lonely'])
  })

  test('maxCoverage and top limit the result', async () => {
    const coverage = parseLcov(LCOV)
    expect(
      (await findTestTargets({ dir, coverage, maxCoverage: 1 })).map((t) => t.fn.name),
    ).toContain('touched')
    expect(await findTestTargets({ dir, coverage, top: 1 })).toHaveLength(1)
  })

  test('produces suggestions with reasons', async () => {
    const [first, second] = await rankTestTargets({
      dir,
      coverage: parseLcov(LCOV),
      churn: new Map([['src/untested.ts', 7]]),
      frameworks: { js: 'bun:test' },
    })
    expect(first).toMatchObject({
      file: 'src/untested.ts',
      symbol: 'lonely',
      kind: 'function',
      range: { start: { line: 1, column: 1 }, end: { line: 5, column: 1 } },
      reason: 'No test covers lonely; 4 lines, changed 7 times in 90 days',
      coverage: { covered: 0, total: 4 },
      churn: 7,
      framework: 'bun:test',
    })
    expect(first?.id).toMatch(/^[0-9a-f]{16}$/)
    expect(second?.reason).toBe('createSession is 17% covered (1 of 6 lines); 8 lines, 2 branches')
  })
})

test('reasonFor and targetScore', () => {
  const target = { covered: 0, total: 30, lines: 42, complexity: 1, churn: 7 }
  expect(
    reasonFor({
      ...target,
      file: 'a.ts',
      score: 0,
      fn: { name: 'createSession', kind: 'function', startLine: 1, endLine: 42, branches: 0 },
    }),
  ).toBe('No test covers createSession; 42 lines, changed 7 times in 90 days')
  expect(targetScore(target)).toBeGreaterThan(targetScore({ ...target, churn: 0 }))
  expect(targetScore(target)).toBeGreaterThan(targetScore({ ...target, covered: 15 }))
  expect(targetScore({ ...target, complexity: 5 })).toBeGreaterThan(targetScore(target))
})
