import { describe, expect, test } from 'bun:test'

import { singleTestCommand, testPathFor, testPathProblem } from './conventions.ts'
import { isExcludedByName, isGeneratedSource, isTestFile, languageOf } from './files.ts'
import type { TestConventions } from './types.ts'

const colocated: TestConventions = {
  language: 'js',
  layout: 'colocated',
  fileName: '{name}.test.ts',
}
const jestDir: TestConventions = {
  language: 'js',
  layout: '__tests__',
  testDir: '__tests__',
  fileName: '{name}.spec.js',
}
const testDir: TestConventions = {
  language: 'js',
  layout: 'test-dir',
  testDir: 'test',
  fileName: '{name}.test.ts',
}
const go: TestConventions = { language: 'go', layout: 'colocated', fileName: '{name}_test.go' }
const py: TestConventions = {
  language: 'python',
  layout: 'test-dir',
  testDir: 'tests',
  fileName: 'test_{name}.py',
}

describe('file classification', () => {
  test('languages and test files', () => {
    expect(languageOf('src/a.tsx')).toBe('js')
    expect(languageOf('src/a.d.ts')).toBeUndefined()
    expect(languageOf('main.go')).toBe('go')
    expect(isTestFile('src/a.test.ts')).toBe(true)
    expect(isTestFile('src/__tests__/a.js')).toBe(true)
    expect(isTestFile('pkg/a_test.go')).toBe(true)
    expect(isTestFile('tests/test_a.py')).toBe(true)
    expect(isTestFile('src/a.ts')).toBe(false)
  })

  test('excluded and generated files', () => {
    expect(isExcludedByName('vite.config.ts')).toBe(true)
    expect(isExcludedByName('api/types.pb.go')).toBe(true)
    expect(isExcludedByName('src/a.ts')).toBe(false)
    expect(isGeneratedSource('// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x')).toBe(
      true,
    )
    expect(isGeneratedSource('/** @generated */\nexport {}')).toBe(true)
    expect(isGeneratedSource('export const a = 1')).toBe(false)
  })
})

describe('testPathFor', () => {
  test('follows each layout', () => {
    expect(testPathFor(colocated, 'src/session.ts')).toBe('src/session.test.ts')
    expect(testPathFor(colocated, 'session.ts')).toBe('session.test.ts')
    expect(testPathFor(jestDir, 'src/session.js')).toBe('src/__tests__/session.spec.js')
    expect(testPathFor(testDir, 'packages/x/src/db/session.ts')).toBe(
      'packages/x/test/db/session.test.ts',
    )
    expect(testPathFor(testDir, 'lib/session.ts')).toBe('test/lib/session.test.ts')
    expect(testPathFor(go, 'internal/calc/calc.go')).toBe('internal/calc/calc_test.go')
    expect(testPathFor(py, 'shop/cart.py')).toBe('tests/test_cart.py')
  })
})

describe('testPathProblem', () => {
  test('accepts conventional paths', () => {
    expect(testPathProblem(colocated, 'src/a.ts', 'src/a.test.ts')).toBeUndefined()
    expect(testPathProblem(colocated, 'src/a.ts', 'src/a.behavior.test.ts')).toBeUndefined()
    expect(testPathProblem(jestDir, 'src/a.js', 'src/__tests__/a.js')).toBeUndefined()
    expect(
      testPathProblem(testDir, 'packages/x/src/a.ts', 'packages/x/test/a.test.ts'),
    ).toBeUndefined()
    expect(testPathProblem(go, 'calc/calc.go', 'calc/discount_test.go')).toBeUndefined()
    expect(testPathProblem(py, 'shop/cart.py', 'tests/test_cart.py')).toBeUndefined()
  })

  test('rejects paths that break the convention or escape the project', () => {
    expect(testPathProblem(colocated, 'src/a.ts', 'test/a.test.ts')).toContain('next to the source')
    expect(testPathProblem(colocated, 'src/a.ts', 'src/a.ts')).toContain('named like')
    expect(testPathProblem(colocated, 'src/a.ts', '../a.test.ts')).toContain('inside the project')
    expect(testPathProblem(colocated, 'src/a.ts', '/tmp/a.test.ts')).toContain('relative')
    expect(testPathProblem(jestDir, 'src/a.js', 'src/a.spec.js')).toContain('__tests__')
    expect(testPathProblem(go, 'calc/calc.go', 'other/calc_test.go')).toContain('package directory')
    expect(testPathProblem(py, 'shop/cart.py', 'shop/cart_check.py')).toContain('test_*.py')
  })
})

test('singleTestCommand', () => {
  expect(singleTestCommand('bun:test', 'src/a.test.ts')).toEqual(['bun', 'test', './src/a.test.ts'])
  expect(singleTestCommand('go test', 'calc/calc_test.go')).toEqual(['go', 'test', './calc'])
  expect(singleTestCommand('pytest', 'tests/test_a.py')).toEqual([
    'python3',
    '-m',
    'pytest',
    'tests/test_a.py',
  ])
})
